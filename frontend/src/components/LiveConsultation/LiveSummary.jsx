import { useState } from "react";
import { deleteJSON } from "../../services/api";
import { forgetConsultation } from "../../services/consultations";
import { liveSummaryReport } from "../../services/reportExport";
import DownloadReportButton from "../Report/DownloadReportButton";

export const TAKEAWAYS_TITLE = "Key Takeaways from the Live Discussion";

// Sections in display order; each is shown only when the summary has that
// field (summaries saved before this format used strengths/weaknesses).
const SECTIONS = [
  ["project_understanding", "Project understanding", "text"],
  ["main_problems", "Main problems identified", "list"],
  ["strengths", "Main strengths", "list"],
  ["weaknesses", "Main weaknesses", "list"],
  ["expert_insights", "Important insights from each expert", "insights"],
  ["agreements", "Points of agreement", "list"],
  ["disagreements", "Key disagreements and how they were resolved", "list"],
  ["decisions", "Important decisions", "list"],
  ["recommended_solution", "Final recommendation", "text"],
  ["next_steps", "Actionable next steps", "ordered"],
  ["risks", "Potential risks", "list"],
  ["unanswered_questions", "Unresolved questions", "list"],
  ["conclusion", "Final consolidated conclusion", "conclusion"],
];

function List({ items }) {
  if (!items?.length) return <p className="text-sm text-gray-400">None raised in the discussion.</p>;
  return (
    <ul className="list-disc pl-5 space-y-1 text-sm text-gray-700">
      {items.map((item, i) => <li key={i}>{item}</li>)}
    </ul>
  );
}

function Section({ number, title, children }) {
  return (
    <div className="py-5 border-b border-slate-100 last:border-0">
      <h4 className="font-semibold text-gray-900">
        <span className="text-indigo-600 mr-2">{number}.</span>{title}
      </h4>
      <div className="mt-2">{children}</div>
    </div>
  );
}

/** Closed live session: summary, preserved transcript, and deletion. */
function LiveSummary({ session, experts, consultation, generating, onRetrySummary, onHide }) {
  const [showTranscript, setShowTranscript] = useState(false);
  const [confirmDelete, setConfirmDelete] = useState(false);
  const [deleteState, setDeleteState] = useState("idle");   // idle | deleting | deleted | error
  const [deleteError, setDeleteError] = useState("");

  const summary = session.summary;

  async function deleteConversation() {
    setDeleteState("deleting");
    try {
      await deleteJSON(`/consultations/${consultation.id}`, { token: consultation.token });
      forgetConsultation(consultation.id);
      setDeleteState("deleted");
    } catch (err) {
      setDeleteError(err.message);
      setDeleteState("error");
    }
  }

  if (deleteState === "deleted") {
    return (
      <div className="bg-white rounded-3xl border border-slate-200 p-8 text-center" role="status">
        <p className="font-semibold">The conversation and its summary were deleted.</p>
        <p className="text-sm text-gray-500 mt-2">Only an anonymous record that a consultation took place is kept, for the usage count.</p>
        <button onClick={onHide} className="mt-5 border px-5 py-2 rounded-full text-sm">Close</button>
      </div>
    );
  }

  return (
    <section className="bg-white rounded-3xl border border-slate-200 shadow-sm overflow-hidden" aria-label="Conversation summary">
      <div className="px-5 sm:px-8 py-6 border-b border-slate-100 bg-indigo-50 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <p className="text-xs font-semibold uppercase tracking-widest text-indigo-600">Session ended</p>
          <h3 className="text-2xl font-bold mt-1">{TAKEAWAYS_TITLE}</h3>
          <p className="text-sm text-gray-500 mt-1">
            Generated by AI from this session's transcript ({session.messages.length} messages). Review before acting on it.
          </p>
        </div>
        <button onClick={onHide} className="border border-slate-300 hover:bg-white px-4 py-2 rounded-full text-sm shrink-0">
          Hide
        </button>
      </div>

      <div className="px-5 sm:px-8 py-4">
        {generating && !summary && (
          <p className="py-10 text-center text-gray-500 animate-pulse" role="status">
            Summarising the discussion...
          </p>
        )}

        {!generating && !summary && (
          <div className="py-8 text-center" role="alert">
            <p className="text-amber-800">{session.summary_error || "The summary isn't available."}</p>
            {session.messages.some((m) => m.role === "expert") && (
              <button
                onClick={onRetrySummary}
                className="mt-4 bg-indigo-600 hover:bg-indigo-700 text-white px-5 py-2 rounded-full text-sm"
              >
                Try generating the summary again
              </button>
            )}
          </div>
        )}

        {summary && (
          <div>
            {summary.agenda_total && summary.agenda_completed < summary.agenda_total && (
              <p className="pt-4 text-sm text-amber-800">
                The discussion ended after {summary.agenda_completed} of {summary.agenda_total} agenda items,
                so these takeaways cover only what was discussed.
              </p>
            )}
            {SECTIONS.filter(([key]) => key in summary).map(([key, title, kind], i) => (
              <Section key={key} number={i + 1} title={title}>
                {kind === "text" && (
                  <p className="text-sm text-gray-700 leading-relaxed">{summary[key] || "Not covered in the discussion."}</p>
                )}
                {kind === "conclusion" && (
                  <p className="text-sm text-gray-800 leading-relaxed font-medium">{summary[key] || "—"}</p>
                )}
                {kind === "list" && <List items={summary[key]} />}
                {kind === "ordered" && (summary[key]?.length ? (
                  <ol className="list-decimal pl-5 space-y-1 text-sm text-gray-700">
                    {summary[key].map((step, n) => <li key={n}>{step}</li>)}
                  </ol>
                ) : <p className="text-sm text-gray-400">None agreed in the discussion.</p>)}
                {kind === "insights" && (summary[key]?.length ? (
                  <ul className="list-disc pl-5 space-y-1 text-sm text-gray-700">
                    {summary[key].map((item, n) => (
                      <li key={n}>{item.expert && <span className="font-semibold">{item.expert}: </span>}{item.insight}</li>
                    ))}
                  </ul>
                ) : <p className="text-sm text-gray-400">None raised in the discussion.</p>)}
              </Section>
            ))}
          </div>
        )}
      </div>

      <div className="px-5 sm:px-8 py-5 border-t border-slate-100 bg-slate-50 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div className="flex flex-wrap items-center gap-4">
          <button
            onClick={() => setShowTranscript((v) => !v)}
            className="text-sm font-medium text-indigo-600 hover:underline text-left"
            aria-expanded={showTranscript}
          >
            {showTranscript ? "Hide full transcript" : "Show full transcript"}
          </button>
          {summary && (
            <DownloadReportButton
              build={() => liveSummaryReport({ session, experts })}
              label="Download summary"
              className="text-sm font-medium text-indigo-600 hover:underline text-left"
            />
          )}
        </div>

        <div className="flex items-center gap-3">
          {!confirmDelete ? (
            <button onClick={() => setConfirmDelete(true)} className="text-sm text-red-600 hover:underline">
              Delete this conversation
            </button>
          ) : (
            <>
              <span className="text-sm text-gray-600">Delete the transcript, summary and project text?</span>
              <button
                onClick={deleteConversation}
                disabled={deleteState === "deleting"}
                className="bg-red-600 hover:bg-red-700 disabled:opacity-60 text-white px-3 py-1.5 rounded-full text-sm"
              >
                {deleteState === "deleting" ? "Deleting..." : "Delete"}
              </button>
              <button onClick={() => setConfirmDelete(false)} className="text-sm text-gray-600 hover:underline">
                Cancel
              </button>
            </>
          )}
        </div>
      </div>

      {deleteState === "error" && (
        <p className="px-8 pb-4 text-sm text-red-600" role="alert">{deleteError}</p>
      )}

      {showTranscript && (
        <div className="px-5 sm:px-8 py-5 border-t border-slate-100 space-y-3 max-h-[480px] overflow-y-auto">
          {session.messages.map((m) => (
            <p key={m.id} className="text-sm">
              <span className="font-semibold">
                {m.role === "client" ? "You" : `${experts[m.expert_key]?.first_name || "Expert"} (${experts[m.expert_key]?.role || "AI expert"})`}:
              </span>{" "}
              <span className="text-gray-700 whitespace-pre-wrap">{m.content}</span>
            </p>
          ))}
        </div>
      )}
    </section>
  );
}

export default LiveSummary;
