// Export reports as Markdown files, built only from what the user actually
// saw: their answers, the AI-generated report, the discussion and the files
// they attached. Nothing is added that the experts didn't say.

const DISCLAIMER = "_AI-generated by ExpertOS. Review it before acting on it._";

function stamp() {
  return new Date().toLocaleString(undefined, { dateStyle: "long", timeStyle: "short" });
}

function slug(text) {
  return (text || "report").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "report";
}

function section(title, body) {
  const text = Array.isArray(body) ? body.filter(Boolean).join("\n") : body;
  return text && String(text).trim() ? `## ${title}\n\n${String(text).trim()}\n` : "";
}

function list(items) {
  return (items || []).filter(Boolean).map((item) => `- ${item}`).join("\n");
}

function transcript(messages, name) {
  const lines = (messages || [])
    .filter((m) => (m.text ?? m.message ?? m.content ?? "").trim())
    .map((m) => {
      const text = (m.text ?? m.message ?? m.content).trim();
      if (m.type === "system") return `_${text}_`;
      return `**${m.sender === "user" || m.role === "user" || m.role === "client" ? "You" : name(m)}:** ${text}`;
    });
  return lines.join("\n\n");
}

function fileList(files) {
  return list((files || []).map((f) => `${f.filename}${f.note ? ` (${f.note})` : ""}`));
}

const LABELS = {
  project_name: "Project name",
  description: "Description",
};

function answersSection(answers) {
  const entries = Object.entries(answers || {}).filter(([, v]) => String(v ?? "").trim());
  return entries.map(([key, value]) => `**${LABELS[key] || key.replace(/_/g, " ")}:** ${value}`).join("\n\n");
}

export function expertRoomReport({ expert, answers, report, messages, files }) {
  const metrics = (report?.metrics || []).map((m) => `| ${m.name} | ${m.value} |`);
  const title = report?.title || `${expert.shortRole} Recommendation`;
  const body = [
    `# ${title}`,
    `${expert.name}, ${expert.role} · ${stamp()}\n\n${DISCLAIMER}\n`,
    section("Your project", answersSection(answers)),
    section("Attached files", fileList(files)),
    section("Recommendation", [report?.recommendation, "", report?.description]),
    metrics.length ? section("What to measure", ["| Metric | Target |", "|---|---|", ...metrics,
      "", "_Suggested targets, not measured results._"]) : "",
    section("Discussion", transcript(messages, (m) => m.expertName || expert.name)),
  ];
  return { filename: `${slug(answers?.project_name || title)}-${slug(expert.shortRole)}.md`, text: body.join("\n") };
}

const ANALYSIS_SECTIONS = [
  ["architecture", "Architecture Overview"],
  ["tech_stack", "Recommended Tech Stack"],
  ["database", "Database Recommendation"],
  ["security", "Security Suggestions"],
  ["deployment", "Deployment Strategy"],
  ["recommendation", "Final Recommendation"],
];

export function consultationReport({ project, analysis, messages, files }) {
  const body = [
    "# ExpertOS Consultation Report",
    `${stamp()}\n\n${DISCLAIMER}\n`,
    section("Your project", project),
    section("Attached files", fileList(files)),
    ...ANALYSIS_SECTIONS.map(([key, title]) => section(title, analysis?.[key])),
    section("Discussion", transcript(messages, (m) => m.expert?.name || "Expert")),
  ];
  return { filename: `${slug(project?.split("\n")[0])}-consultation.md`, text: body.join("\n") };
}

export function liveSummaryReport({ session, experts }) {
  const s = session.summary || {};
  const name = (m) => {
    const e = experts[m.expert_key];
    return e ? `${e.first_name} (${e.role})` : "Expert";
  };
  const early = s.agenda_total && s.agenda_completed < s.agenda_total
    ? `_The discussion ended after ${s.agenda_completed} of ${s.agenda_total} agenda items._\n`
    : "";
  const body = [
    "# Key Takeaways from the Live Discussion",
    `${stamp()}\n\n${DISCLAIMER}\n`,
    early,
    section("Project understanding", s.project_understanding),
    section("Main problems identified", list(s.main_problems)),
    section("Main strengths", list(s.strengths)),
    section("Main weaknesses", list(s.weaknesses)),
    section("Important insights from each expert",
      list((s.expert_insights || []).map((i) => (i.expert ? `**${i.expert}:** ${i.insight}` : i.insight)))),
    section("Points of agreement", list(s.agreements)),
    section("Key disagreements and how they were resolved", list(s.disagreements)),
    section("Important decisions", list(s.decisions)),
    section("Final recommendation", s.recommended_solution),
    section("Actionable next steps", (s.next_steps || []).map((step, i) => `${i + 1}. ${step}`).join("\n")),
    section("Potential risks", list(s.risks)),
    section("Unresolved questions", list(s.unanswered_questions)),
    section("Final consolidated conclusion", s.conclusion),
    section("Full transcript", transcript(session.messages, name)),
  ];
  return { filename: "live-discussion-key-takeaways.md", text: body.join("\n") };
}

export function downloadReport({ filename, text }) {
  const blob = new Blob([text], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.href = url;
  link.download = filename;
  document.body.appendChild(link);
  link.click();
  link.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
